// Builds the OpenClaw plugin package in plugins/openclaw/ from the repository root.
//
// ClawHub publishes it as a `bundle-plugin` (docs/publishing.md and docs/cli.md in openclaw/clawhub):
// - Exactly one bundle marker. This package uses the Claude marker, `.claude-plugin/plugin.json`;
//   no `openclaw.plugin.json` (that turns it into a native plugin) and no root `plugin.json`.
// - OpenClaw only signs in to an HTTP MCP server whose entry says `auth: "oauth"`. The Agent
//   Plugins `mcp.json` schema cannot carry that key, and the Claude Code plugin cannot carry it
//   safely, so this package declares the server inline in its own marker.
// - ClawHub takes the listing summary and version from `package.json`, the display name from
//   `package.json.displayName`, and catalog artwork only from `assets/icon.png` (PNG, <= 512 KiB).
//
// The directory is committed because ClawHub's reusable publish workflow reads it from the GitHub
// source at the published commit. Do not edit it by hand.
//
// Usage: node scripts/openclaw-plugin/build.mjs          write plugins/openclaw/
//        node scripts/openclaw-plugin/build.mjs --check  exit 1 when plugins/openclaw/ is stale or invalid

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { DESCRIPTION } from "../manifest/brand.mjs";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const OUTPUT_DIR_NAME = join("plugins", "openclaw");
export const PACKAGE_NAME = "@chatbotx/chatbotx";
export const DISPLAY_NAME = "ChatbotX";
export const MCP_URL = "https://app.chatbotx.io/mcp/messages";
export const ICON_MAX_BYTES = 512 * 1024;
const MARKER = ".claude-plugin/plugin.json";
const BUNDLE_MARKERS = Object.freeze([".codex-plugin/plugin.json", ".claude-plugin/plugin.json", ".cursor-plugin/plugin.json"]);
const FORBIDDEN_FILES = Object.freeze(["openclaw.plugin.json", "plugin.json", "mcp.json", ".mcp.json"]);
const ICON_SOURCE = join("plugins", "chatbotx", ".claude-plugin", "icon.png");
const ICON_TARGET = "assets/icon.png";
const EXCLUDED_FILES = Object.freeze(["skill-card.md", ".DS_Store"]);
const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
const SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/;

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function toJson(value) {
  return Buffer.from(`${JSON.stringify(value, null, 2)}\n`);
}

function listFiles(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((entry) => {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) return listFiles(full);
      return EXCLUDED_FILES.includes(entry.name) ? [] : [full];
    });
}

const toPosix = (path) => path.split(sep).join("/");

export function buildMarker(root) {
  return {
    name: root.name,
    displayName: DISPLAY_NAME,
    version: root.version,
    description: DESCRIPTION,
    author: root.author,
    homepage: root.homepage,
    repository: root.repository,
    license: root.license,
    keywords: root.keywords,
    documentationUrl: "https://chatbotx.io/docs",
    supportUrl: "https://chatbotx.io/contact/",
    privacyPolicyUrl: "https://chatbotx.io/privacy/",
    termsOfServiceUrl: "https://chatbotx.io/terms/",
    mcpServers: {
      chatbotx: { type: "http", url: MCP_URL, auth: "oauth" },
    },
  };
}

export function buildPackageJson(root) {
  return {
    name: PACKAGE_NAME,
    displayName: DISPLAY_NAME,
    version: root.version,
    description: DESCRIPTION,
    homepage: root.homepage,
    repository: { type: "git", url: `git+${root.repository}.git`, directory: "plugins/openclaw" },
    license: root.license,
    author: root.author,
    keywords: root.keywords,
  };
}

export function buildReadme(root) {
  return [
    `# ${DISPLAY_NAME}`,
    "",
    DESCRIPTION,
    "",
    "OpenClaw plugin for [ChatbotX](https://chatbotx.io). It connects the hosted ChatbotX MCP server",
    `(\`${MCP_URL}\`, Streamable HTTP, OAuth) and loads two skills:`,
    "",
    "- `chatbotx-mcp`: how to use the ChatbotX MCP tools, sign in, and approve `CONFIRMATION_REQUIRED` actions.",
    "- `chatbotx`: the `chatbotx` CLI. OpenClaw only enables it when the `chatbotx` binary is installed",
    "  (`npm install -g chatbotx`).",
    "",
    "## Install",
    "",
    "```bash",
    `openclaw plugins install clawhub:${PACKAGE_NAME}`,
    "openclaw mcp login chatbotx",
    "```",
    "",
    "Sign in with your ChatbotX account in the browser and pick one workspace on the consent screen",
    "(workspace owners only). No API key is stored. Revoke access in ChatbotX → Settings →",
    "Integrations → ChatbotX MCP. Tools appear as `chatbotx__<tool>` in the next agent session.",
    "",
    "## Source",
    "",
    `Generated by \`npm run build:openclaw-plugin\` in ${root.repository}. Do not edit this directory:`,
    "edit `skills/` or `scripts/manifest/brand.mjs` and rebuild.",
    "",
  ].join("\n");
}

// Collects the package as a Map of POSIX relative path -> Buffer.
export function collectPackage({ repoRoot = REPO_ROOT } = {}) {
  const root = readJson(join(repoRoot, "plugin.json"));
  const files = new Map();
  files.set(MARKER, toJson(buildMarker(root)));
  files.set("package.json", toJson(buildPackageJson(root)));
  files.set("README.md", Buffer.from(buildReadme(root)));
  files.set("LICENSE", readFileSync(join(repoRoot, "LICENSE")));
  files.set(ICON_TARGET, readFileSync(join(repoRoot, ICON_SOURCE)));
  const skillsDir = join(repoRoot, "skills");
  for (const file of listFiles(skillsDir)) {
    files.set(`skills/${toPosix(relative(skillsDir, file))}`, readFileSync(file));
  }
  return files;
}

function parseJsonFile(files, path, problems) {
  try {
    return JSON.parse(files.get(path).toString("utf8"));
  } catch (cause) {
    problems.push(`${path}: invalid JSON (${cause.message})`);
    return undefined;
  }
}

function checkMarker(marker, problems) {
  if (typeof marker.name !== "string" || !/^[a-z0-9][a-z0-9-]*$/.test(marker.name)) {
    problems.push(`${MARKER}: name must be a lowercase id`);
  }
  if (marker.description !== DESCRIPTION) problems.push(`${MARKER}: description differs from brand.mjs`);
  const servers = Object.entries(marker.mcpServers ?? {});
  if (servers.length === 0) problems.push(`${MARKER}: no mcpServers`);
  for (const [name, server] of servers) {
    if (server.type !== "http") problems.push(`${MARKER}: mcpServers.${name}.type must be "http"`);
    if (!String(server.url ?? "").startsWith("https://")) problems.push(`${MARKER}: mcpServers.${name}.url must be https`);
    if (server.auth !== "oauth") problems.push(`${MARKER}: mcpServers.${name}.auth must be "oauth"`);
    if (server.headers !== undefined) problems.push(`${MARKER}: mcpServers.${name} must not carry headers`);
  }
}

function checkPackageJson(pkg, marker, problems) {
  if (pkg.name !== PACKAGE_NAME) problems.push(`package.json: name must be ${PACKAGE_NAME}`);
  if (pkg.description !== DESCRIPTION) problems.push("package.json: description differs from brand.mjs");
  if (!SEMVER.test(pkg.version ?? "")) problems.push("package.json: version must be semver");
  if (marker && pkg.version !== marker.version) problems.push("package.json: version differs from the bundle marker");
  if (pkg.openclaw !== undefined) problems.push("package.json: must not declare `openclaw` (makes a native plugin)");
}

// Validates a package (Map of path -> Buffer) against the ClawHub bundle-plugin rules this repo
// relies on. Returns a list of problems; empty means valid.
export function verifyPackage(files) {
  const problems = [];
  const markers = BUNDLE_MARKERS.filter((path) => files.has(path));
  if (markers.length !== 1 || markers[0] !== MARKER) {
    problems.push(`expected exactly one bundle marker (${MARKER}), found: ${markers.join(", ") || "none"}`);
  }
  for (const path of FORBIDDEN_FILES) {
    if (files.has(path)) problems.push(`${path} must not be in the package`);
  }
  const marker = files.has(MARKER) ? parseJsonFile(files, MARKER, problems) : undefined;
  if (marker) checkMarker(marker, problems);
  if (!files.has("package.json")) {
    problems.push("package.json missing");
  } else {
    const pkg = parseJsonFile(files, "package.json", problems);
    if (pkg) checkPackageJson(pkg, marker, problems);
  }
  const icon = files.get(ICON_TARGET);
  if (!icon) problems.push(`${ICON_TARGET} missing`);
  else if (!icon.subarray(0, 8).equals(PNG_SIGNATURE)) problems.push(`${ICON_TARGET} is not a PNG`);
  else if (icon.length > ICON_MAX_BYTES) problems.push(`${ICON_TARGET} is larger than ${ICON_MAX_BYTES} bytes`);
  const skills = new Set([...files.keys()].filter((p) => p.startsWith("skills/")).map((p) => p.split("/")[1]));
  if (skills.size === 0) problems.push("no skill shipped");
  for (const skill of skills) {
    if (!files.has(`skills/${skill}/SKILL.md`)) problems.push(`skills/${skill}/SKILL.md missing`);
  }
  return problems;
}

export function readPackage(dir) {
  if (!existsSync(dir)) return new Map();
  return new Map(listFiles(dir).map((file) => [toPosix(relative(dir, file)), readFileSync(file)]));
}

export function findDrift(expected, actual) {
  const paths = new Set([...expected.keys(), ...actual.keys()]);
  return [...paths]
    .filter((path) => {
      const want = expected.get(path);
      const have = actual.get(path);
      return !want || !have || !want.equals(have);
    })
    .sort();
}

function main() {
  const outDir = join(REPO_ROOT, OUTPUT_DIR_NAME);
  const expected = collectPackage();
  const problems = verifyPackage(expected);
  if (problems.length > 0) throw new Error(`OpenClaw package is invalid:\n  ${problems.join("\n  ")}`);
  if (process.argv.includes("--check")) {
    const drift = findDrift(expected, readPackage(outDir));
    if (drift.length > 0) {
      throw new Error(`${OUTPUT_DIR_NAME} is out of date:\n  ${drift.join("\n  ")}\nRun: npm run build:openclaw-plugin`);
    }
    return;
  }
  rmSync(outDir, { recursive: true, force: true });
  for (const [path, content] of expected) {
    const target = join(outDir, path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
  console.log(`${OUTPUT_DIR_NAME}: ${expected.size} files, ${PACKAGE_NAME}@${readJson(join(outDir, "package.json")).version}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (cause) {
    console.error(cause.message);
    process.exit(1);
  }
}
